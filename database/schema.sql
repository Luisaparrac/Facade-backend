CREATE TABLE IF NOT EXISTS patients (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type    VARCHAR(20)  NOT NULL,
    document_number  VARCHAR(20)  NOT NULL UNIQUE,
    first_name       VARCHAR(60)  NOT NULL,
    last_name        VARCHAR(60)  NOT NULL,
    birth_date       DATE         NOT NULL,
    email            VARCHAR(120) NOT NULL UNIQUE,
    phone            VARCHAR(20),
    password_hash    VARCHAR(100) NOT NULL,
    created_at       TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS doctors (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        VARCHAR(100) NOT NULL,
    specialty        VARCHAR(30)  NOT NULL,
    license_number   VARCHAR(20)  NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS appointments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       BIGINT       NOT NULL REFERENCES patients (id),
    doctor_id        BIGINT       NOT NULL REFERENCES doctors (id),
    date_time        TIMESTAMP    NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    reason           VARCHAR(200),
    created_at       TIMESTAMP    NOT NULL,
    cancelled_at     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_appointments_doctor_time ON appointments (doctor_id, date_time);
CREATE INDEX IF NOT EXISTS idx_appointments_patient ON appointments (patient_id);

CREATE TABLE IF NOT EXISTS consultations (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id         BIGINT       NOT NULL REFERENCES patients (id),
    doctor_name        VARCHAR(100) NOT NULL,
    specialty          VARCHAR(30)  NOT NULL,
    consultation_date  TIMESTAMP    NOT NULL,
    reason             VARCHAR(200) NOT NULL,
    diagnosis          VARCHAR(200) NOT NULL,
    notes              VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS idx_consultations_patient ON consultations (patient_id);

CREATE TABLE IF NOT EXISTS allergies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       BIGINT       NOT NULL REFERENCES patients (id),
    substance        VARCHAR(80)  NOT NULL,
    reaction         VARCHAR(120)
);
CREATE INDEX IF NOT EXISTS idx_allergies_patient ON allergies (patient_id);

CREATE TABLE IF NOT EXISTS prescriptions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       BIGINT       NOT NULL REFERENCES patients (id),
    doctor_name      VARCHAR(100) NOT NULL,
    diagnosis        VARCHAR(200),
    issued_at        TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_prescriptions_patient ON prescriptions (patient_id);

CREATE TABLE IF NOT EXISTS prescription_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id  BIGINT       NOT NULL REFERENCES prescriptions (id) ON DELETE CASCADE,
    medication       VARCHAR(100) NOT NULL,
    dose             VARCHAR(60)  NOT NULL,
    frequency        VARCHAR(60)  NOT NULL,
    duration_days    INTEGER      NOT NULL,
    instructions     VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS lab_orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       BIGINT       NOT NULL REFERENCES patients (id),
    requested_at     TIMESTAMP    NOT NULL,
    completed_at     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_lab_orders_patient ON lab_orders (patient_id);

CREATE TABLE IF NOT EXISTS lab_results (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_order_id     BIGINT           NOT NULL REFERENCES lab_orders (id) ON DELETE CASCADE,
    exam_type        VARCHAR(30)      NOT NULL,
    parameter_name   VARCHAR(60)      NOT NULL,
    result_value     DOUBLE PRECISION NOT NULL,
    unit             VARCHAR(20)      NOT NULL,
    reference_min    DOUBLE PRECISION NOT NULL,
    reference_max    DOUBLE PRECISION NOT NULL,
    status           VARCHAR(10)      NOT NULL
);

CREATE TABLE IF NOT EXISTS session_tokens (
    token_hash       VARCHAR(64)  PRIMARY KEY,
    patient_id       BIGINT       NOT NULL REFERENCES patients (id),
    created_at       TIMESTAMP    NOT NULL,
    expires_at       TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_prescription_items_prescription ON prescription_items (prescription_id);
CREATE INDEX IF NOT EXISTS idx_lab_results_order ON lab_results (lab_order_id);
CREATE INDEX IF NOT EXISTS idx_session_tokens_patient ON session_tokens (patient_id);
